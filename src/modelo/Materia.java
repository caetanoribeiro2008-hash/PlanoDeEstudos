
package modelo;

public class Materia {

    private boolean matematica;
    private boolean fisica;
    private boolean quimica;
    private boolean biologia;
    private boolean portugues;
    private boolean literatura;
    private boolean geografia;
    private boolean historia;

    public boolean isMatematica() {
        return matematica;
    }

    public void setMatematica(boolean matematica) {
        this.matematica = matematica;
    }

    
    public boolean isFisica() {
        return fisica;
    }

    public void setFisica(boolean fisica) {
        this.fisica = fisica;
    }

   
    public boolean isQuimica() {
        return quimica;
    }

    public void setQuimica(boolean quimica) {
        this.quimica = quimica;
    }

    
    public boolean isBiologia() {
        return biologia;
    }

    public void setBiologia(boolean biologia) {
        this.biologia = biologia;
    }

   
    public boolean isPortugues() {
        return portugues;
    }

    public void setPortugues(boolean portugues) {
        this.portugues = portugues;
    }

    public boolean isLiteratura() {
        return literatura;
    }

    public void setLiteratura(boolean literatura) {
        this.literatura = literatura;
    }

    
    public boolean isGeografia() {
        return geografia;
    }

    public void setGeografia(boolean geografia) {
        this.geografia = geografia;
    }

   
    public boolean isHistoria() {
        return historia;
    }

    public void setHistoria(boolean historia) {
        this.historia = historia;
    }
}

   