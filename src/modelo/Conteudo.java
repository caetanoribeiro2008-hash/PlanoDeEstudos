
package modelo;


public class Conteudo {
    private String materia;
    private String nome;

    public Conteudo(String materia, String nome) {
        this.materia = materia;
        this.nome = nome;
    }

    public String getMateria() {
        return materia;
    }

    public String getNome() {
        return nome;
    }
}
